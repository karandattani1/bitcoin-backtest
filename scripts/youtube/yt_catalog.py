"""Merge every strategy.json into one catalog, grouping near-duplicate strategies.

    python scripts/youtube/yt_catalog.py

Writes data/youtube/catalog.csv (one row per extracted strategy) and
research/youtube-strategy-catalog.md (groups of similar strategies, with source links).
"""
import argparse
import csv
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def leg_signature(legs: list[dict]) -> str:
    """e.g. 'sell CE ATM + sell PE ATM' -> grouping key that ignores wording differences."""
    parts = []
    for leg in legs:
        strike = (leg.get("strike_rule") or "?").upper()
        strike = "ATM" if "ATM" in strike and not re.search(r"[+-]", strike) else (
            "DELTA" if "DELTA" in strike else "OTM" if re.search(r"OTM|[+-]\s*\d", strike) else strike[:12]
        )
        parts.append(f"{leg['action']} {leg['instrument']} {strike}")
    return " + ".join(sorted(parts)) or "no legs"


def group_key(s: dict) -> tuple:
    entry = (s.get("entry_time") or "").strip().lower()
    return (s["category"], s["market"], (s.get("underlying") or "?").upper()[:12], entry[:8], leg_signature(s["legs"]))


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--data", default=str(ROOT / "data" / "youtube"))
    p.add_argument("--out", default=str(ROOT / "research" / "youtube-strategy-catalog.md"))
    p.add_argument("--min-completeness", type=float, default=0.0)
    args = p.parse_args()

    rows = []
    for f in sorted(Path(args.data).glob("*/*/strategy.json")):
        doc = json.loads(f.read_text())
        for s in doc.get("strategies", []):
            if s.get("completeness", 0) < args.min_completeness:
                continue
            s["_video"] = doc["video"]
            s["_channel_dir"] = f.parent.parent.name
            rows.append(s)

    with open(Path(args.data) / "catalog.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["channel", "video", "url", "uploaded", "name", "category", "market", "underlying",
                    "entry_time", "legs", "entry_conditions", "stop_loss", "target", "exit_rules",
                    "filters", "completeness", "missing_for_backtest", "obsolete_in_india_2026"])
        for s in rows:
            w.writerow([
                s["_channel_dir"], s["_video"]["title"], s["_video"]["url"], s["_video"]["upload_date"],
                s["name"], s["category"], s["market"], s.get("underlying"), s.get("entry_time"),
                leg_signature(s["legs"]), " | ".join(s["entry_conditions"]), s.get("stop_loss"), s.get("target"),
                " | ".join(s["exit_rules"]), " | ".join(s["filters"]), s.get("completeness"),
                " | ".join(s["missing_for_backtest"]), s.get("obsolete_in_india_2026"),
            ])

    groups = defaultdict(list)
    for s in rows:
        groups[group_key(s)].append(s)
    ordered = sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0]))

    out = ["# YouTube strategy catalog", "",
           f"*Generated by `scripts/youtube/yt_catalog.py` from {len(rows)} extracted strategies "
           f"in {len(groups)} groups. Claims are as stated in the videos and have not been verified.*", ""]
    for (category, market, underlying, entry, legs), items in ordered:
        best = max(items, key=lambda s: s.get("completeness", 0))
        out += [f"## {best['name']}  ({len(items)} video{'s' if len(items) > 1 else ''})", "",
                f"- **Group:** {category} · {market} · {underlying} · entry {entry or '?'} · {legs}",
                f"- **Entry:** " + ("; ".join(best["entry_conditions"]) or "?"),
                f"- **Stop / target:** {best.get('stop_loss') or '?'} / {best.get('target') or '?'}",
                f"- **Exit:** " + ("; ".join(best["exit_rules"]) or "?"),
                f"- **Filters:** " + ("; ".join(best["filters"]) or "none stated")]
        variants = sorted({(s.get('stop_loss') or '?', s.get('target') or '?') for s in items})
        if len(variants) > 1:
            out.append("- **Parameter variants seen (SL / target):** " +
                       "; ".join(f"{sl} / {tg}" for sl, tg in variants[:8]))
        if best.get("obsolete_in_india_2026"):
            out.append(f"- **Obsolete in India 2026:** {best['obsolete_in_india_2026']}")
        if best["missing_for_backtest"]:
            out.append("- **Missing for backtest:** " + "; ".join(best["missing_for_backtest"]))
        out.append("- **Sources:** " + ", ".join(
            f"[{s['_channel_dir']}: {s['_video']['title'][:50]}]({s['_video']['url']})" for s in items[:6]))
        out.append("")
    Path(args.out).write_text("\n".join(out))
    print(f"{len(rows)} strategies, {len(groups)} groups")


if __name__ == "__main__":
    main()
